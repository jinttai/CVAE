"""
Dataset generation bias analysis.

The collision-free dataset was generated by:
  Phase 1: 1000 random seeds, init_scale=0.3 -> Adam + LBFGS
  Phase 2: Perturb each converged seed by perturb_scale=0.2 -> LBFGS

Possible bias sources:
  (B1) init_scale=0.3 too small -> Phase 1 only explores near-origin basins
  (B2) perturb_scale=0.2 too small -> Phase 2 creates tight clusters around seeds
  (B3) Only few Phase 1 seeds survive -> dataset dominated by those seed types
  (B4) Seed pool cap (500) + perturb growth -> late batches depend on early ones

Tests:
  1. Distribution of nearest-seed distance (tight clustering around seeds?)
  2. Waypoint joint coverage vs expected safe range
  3. Birth cluster detection — how many distinct "seed types" dominate?
  4. Diversity over time (is dataset growing more varied?)
  5. Compare 5000 vs 20000 to see if bias evolves
"""

import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import os
from sklearn.cluster import KMeans
from sklearn.decomposition import PCA
from sklearn.neighbors import NearestNeighbors
from scipy.spatial.distance import cdist

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), "../.."))
SAVE = os.path.join(ROOT, "outputs/results/dataset_bias_analysis")
os.makedirs(SAVE, exist_ok=True)

WP_INDICES = [24, 49, 74]
JOINT_LOWER = np.array([-2.0, -2.0, -2.5, -2.5, -2.0, -3.0])
JOINT_UPPER = np.array([3.5, 2.0, 3.0, 2.5, 2.2, 3.0])


def extract_wp(data):
    return data[:, WP_INDICES, :].reshape(data.shape[0], -1)


# ==================== Test 1: Seed-based clustering ====================

def seed_tightness_test(wp_flat, label, n_seeds_try=[5, 10, 20, 50, 100]):
    """
    If dataset has seed-based bias, low-k KMeans should fit tightly
    (small within-cluster distance, tight spheres) with perturb_scale-sized radii.
    """
    print(f"\n--- {label}: seed-tightness test ---")
    print(f"{'n_seeds':>8} {'mean_radius':>14} {'std_radius':>12} {'max_radius':>12}")
    results = []
    for k in n_seeds_try:
        km = KMeans(n_clusters=k, n_init=5, random_state=42).fit(wp_flat)
        # Radius = mean distance from each point to its assigned centroid
        dists = np.linalg.norm(wp_flat - km.cluster_centers_[km.labels_], axis=1)
        per_cluster_radii = [dists[km.labels_ == c].mean()
                              for c in range(k)]
        mean_r = np.mean(per_cluster_radii)
        std_r = np.std(per_cluster_radii)
        max_r = np.max(per_cluster_radii)
        results.append({"k": k, "mean_r": mean_r, "std_r": std_r, "max_r": max_r})
        print(f"{k:>8d} {mean_r:>14.3f} {std_r:>12.3f} {max_r:>12.3f}")

    # Expected if perturb-only-noise: clusters of radius ~ sqrt(18) * 0.2 ~ 0.85
    # (perturb_scale=0.2, 18 dims)
    expected_perturb_radius = np.sqrt(18) * 0.2
    print(f"  Expected radius if pure perturb (sqrt(18)*0.2): {expected_perturb_radius:.2f}")
    return results


# ==================== Test 2: Joint range coverage ====================

def joint_coverage_test(wp_flat, label):
    """
    Does the dataset cover the safe joint range uniformly?
    If biased toward certain seeds, coverage will be uneven (bimodal/multimodal).
    """
    print(f"\n--- {label}: joint coverage ---")
    N = wp_flat.shape[0]
    wp_3d = wp_flat.reshape(N, 3, 6)

    coverage = np.zeros(6)  # fraction of safe range covered
    for j in range(6):
        vals = wp_3d[:, :, j].flatten()
        v_range = vals.max() - vals.min()
        safe_range = JOINT_UPPER[j] - JOINT_LOWER[j]
        coverage[j] = v_range / safe_range
        # Check uniformity via histogram entropy
        hist, _ = np.histogram(vals, bins=20, range=(JOINT_LOWER[j], JOINT_UPPER[j]))
        probs = hist / (hist.sum() + 1e-12)
        probs = probs[probs > 0]
        entropy = -np.sum(probs * np.log(probs))
        max_entropy = np.log(20)
        uniformity = entropy / max_entropy
        print(f"  Joint {j}: range={v_range:.2f}/{safe_range:.2f} "
              f"({coverage[j]*100:.0f}%)  "
              f"uniformity={uniformity:.2f}  "
              f"({'OK' if uniformity > 0.8 else 'BIASED' if uniformity < 0.6 else 'mild bias'})")

    return coverage


# ==================== Test 3: Simulate random baseline ====================

def simulate_random_baseline(n_samples, label):
    """Sample uniformly from safe joint range. Compare to real dataset."""
    print(f"\n--- {label}: uniform-null baseline ---")
    rng = np.random.default_rng(42)
    # Random waypoints uniform in safe range
    wp_3d = np.empty((n_samples, 3, 6))
    for j in range(6):
        wp_3d[:, :, j] = rng.uniform(JOINT_LOWER[j], JOINT_UPPER[j],
                                       size=(n_samples, 3))
    wp_flat = wp_3d.reshape(n_samples, 18)
    return wp_flat


# ==================== Test 4: Distance distribution ====================

def distance_dist(wp_flat, label, n_sub=2000):
    """Pairwise distance distribution — compare modes."""
    rng = np.random.default_rng(42)
    idx = rng.choice(len(wp_flat), min(n_sub, len(wp_flat)), replace=False)
    X = wp_flat[idx]
    dists = cdist(X, X)
    # Take upper triangle only
    triu = dists[np.triu_indices(len(X), k=1)]
    return triu


# ==================== Test 5: Density histogram ====================

def density_structure_test(wp_flat, label):
    """Look at PC1 density. Real clustering = multimodal. Seed-bias = sharp spikes."""
    pca = PCA(n_components=3).fit(wp_flat)
    X = pca.transform(wp_flat)
    return X, pca.explained_variance_ratio_


# ==================== Main ====================

def main():
    print("=== Dataset Bias Analysis ===\n")

    d_5k = np.load(os.path.join(ROOT, "outputs/results/collision_free_dataset/trajectories_collision_free_5000x100x6.npy"))
    d_20k = np.load(os.path.join(ROOT, "outputs/results/collision_free_dataset/trajectories_collision_free_20000x100x6.npy"))

    wp_5k = extract_wp(d_5k)
    wp_20k = extract_wp(d_20k)

    # Simulated uniform baseline for comparison
    wp_uniform = simulate_random_baseline(5000, "uniform null")

    # ---- Test 1: Seed-tightness ----
    print("\n" + "=" * 72)
    print("TEST 1: Cluster tightness (Is dataset = tight balls around few seeds?)")
    print("=" * 72)
    r5 = seed_tightness_test(wp_5k, "5k Col-Free")
    r20 = seed_tightness_test(wp_20k, "20k Col-Free")
    ru = seed_tightness_test(wp_uniform, "uniform null (unbiased)")

    # ---- Test 2: Joint coverage ----
    print("\n" + "=" * 72)
    print("TEST 2: Joint range coverage (uniform = no bias)")
    print("=" * 72)
    c5 = joint_coverage_test(wp_5k, "5k Col-Free")
    c20 = joint_coverage_test(wp_20k, "20k Col-Free")
    cu = joint_coverage_test(wp_uniform, "uniform null")

    # ---- Test 3: Distance distribution comparison ----
    print("\n" + "=" * 72)
    print("TEST 3: Pairwise distance distribution")
    print("=" * 72)
    d_5k_dist = distance_dist(wp_5k, "5k")
    d_20k_dist = distance_dist(wp_20k, "20k")
    d_u_dist = distance_dist(wp_uniform, "uniform")
    print(f"  5k  distances:    mean={d_5k_dist.mean():.2f}  std={d_5k_dist.std():.2f}")
    print(f"  20k distances:    mean={d_20k_dist.mean():.2f}  std={d_20k_dist.std():.2f}")
    print(f"  uniform distances: mean={d_u_dist.mean():.2f}  std={d_u_dist.std():.2f}")
    print(f"  uniform expected std/mean ~ 0.25 for uniform cube")
    print(f"  5k  std/mean: {d_5k_dist.std()/d_5k_dist.mean():.3f}")
    print(f"  20k std/mean: {d_20k_dist.std()/d_20k_dist.mean():.3f}")
    print(f"  uniform std/mean: {d_u_dist.std()/d_u_dist.mean():.3f}")

    # ---- Test 4: PCA structure comparison ----
    X_5k, var_5k = density_structure_test(wp_5k, "5k")
    X_20k, var_20k = density_structure_test(wp_20k, "20k")
    X_u, var_u = density_structure_test(wp_uniform, "uniform")

    # ---- Plots ----
    # 4x3 grid: rows = 5k / 20k / uniform,  cols = pc1-pc2 / joint-hist / dist-dist
    fig = plt.figure(figsize=(16, 12))

    # Row 1: 5k
    ax = fig.add_subplot(3, 3, 1)
    ax.scatter(X_5k[:, 0], X_5k[:, 1], s=2, alpha=0.25, color='tab:blue')
    ax.set_title(f"5k Col-Free: PC1-PC2\nvar={var_5k[:2].sum()*100:.0f}%")
    ax.grid(alpha=0.3)

    ax = fig.add_subplot(3, 3, 2)
    wp3d = wp_5k.reshape(-1, 3, 6)
    for j in range(6):
        ax.hist(wp3d[:, :, j].flatten(), bins=40, alpha=0.35,
                label=f"J{j}", range=(-5, 5))
    ax.set_title("5k joint 0..5 histograms"); ax.legend(fontsize=7); ax.grid(alpha=0.3)

    ax = fig.add_subplot(3, 3, 3)
    ax.hist(d_5k_dist, bins=60, density=True, alpha=0.7, color='tab:blue')
    ax.set_title("5k pairwise distances")
    ax.set_xlabel("L2 distance"); ax.grid(alpha=0.3)

    # Row 2: 20k
    ax = fig.add_subplot(3, 3, 4)
    ax.scatter(X_20k[:, 0], X_20k[:, 1], s=1, alpha=0.15, color='tab:orange')
    ax.set_title(f"20k Col-Free: PC1-PC2\nvar={var_20k[:2].sum()*100:.0f}%")
    ax.grid(alpha=0.3)

    ax = fig.add_subplot(3, 3, 5)
    wp3d = wp_20k.reshape(-1, 3, 6)
    for j in range(6):
        ax.hist(wp3d[:, :, j].flatten(), bins=40, alpha=0.35,
                label=f"J{j}", range=(-5, 5))
    ax.set_title("20k joint 0..5 histograms"); ax.legend(fontsize=7); ax.grid(alpha=0.3)

    ax = fig.add_subplot(3, 3, 6)
    ax.hist(d_20k_dist, bins=60, density=True, alpha=0.7, color='tab:orange')
    ax.set_title("20k pairwise distances")
    ax.set_xlabel("L2 distance"); ax.grid(alpha=0.3)

    # Row 3: uniform
    ax = fig.add_subplot(3, 3, 7)
    ax.scatter(X_u[:, 0], X_u[:, 1], s=2, alpha=0.25, color='gray')
    ax.set_title(f"Uniform null (unbiased): PC1-PC2\nvar={var_u[:2].sum()*100:.0f}%")
    ax.grid(alpha=0.3)

    ax = fig.add_subplot(3, 3, 8)
    wp3d = wp_uniform.reshape(-1, 3, 6)
    for j in range(6):
        ax.hist(wp3d[:, :, j].flatten(), bins=40, alpha=0.35,
                label=f"J{j}", range=(-5, 5))
    ax.set_title("Uniform joint histograms (flat)"); ax.legend(fontsize=7); ax.grid(alpha=0.3)

    ax = fig.add_subplot(3, 3, 9)
    ax.hist(d_u_dist, bins=60, density=True, alpha=0.7, color='gray')
    ax.set_title("Uniform pairwise distances (bell-shape)")
    ax.set_xlabel("L2 distance"); ax.grid(alpha=0.3)

    plt.suptitle("Dataset bias diagnostic: 5k vs 20k vs uniform null", fontsize=13)
    plt.tight_layout()
    plt.savefig(os.path.join(SAVE, "bias_diagnostic.png"), dpi=150)
    plt.close()
    print(f"\nSaved: {os.path.join(SAVE, 'bias_diagnostic.png')}")

    # ---- Tightness vs k comparison plot ----
    fig, ax = plt.subplots(figsize=(10, 5))
    ks = [5, 10, 20, 50, 100]
    ax.plot(ks, [r['mean_r'] for r in r5], 'o-', label='5k Col-Free', color='tab:blue')
    ax.plot(ks, [r['mean_r'] for r in r20], 's-', label='20k Col-Free', color='tab:orange')
    ax.plot(ks, [r['mean_r'] for r in ru], '^-', label='Uniform null', color='gray')
    ax.axhline(np.sqrt(18) * 0.2, color='red', linestyle='--',
                label=f'perturb_scale sqrt(18)*0.2 = {np.sqrt(18)*0.2:.2f}')
    ax.set_xlabel("k (# clusters)")
    ax.set_ylabel("Mean within-cluster radius")
    ax.set_title("Cluster tightness: if data = perturbed seeds, should hit red line")
    ax.legend(); ax.grid(alpha=0.3)
    ax.set_xscale('log')
    plt.tight_layout()
    plt.savefig(os.path.join(SAVE, "tightness_vs_k.png"), dpi=150)
    plt.close()
    print(f"Saved: {os.path.join(SAVE, 'tightness_vs_k.png')}")

    # ---- Final summary ----
    print(f"\n{'='*72}")
    print("BIAS VERDICT")
    print(f"{'='*72}")
    print(f"{'Metric':<40} {'5k':>10} {'20k':>10} {'Uniform':>10}")
    print(f"{'coverage (mean of 6 joints)':<40} "
          f"{c5.mean()*100:>9.0f}% {c20.mean()*100:>9.0f}% {cu.mean()*100:>9.0f}%")
    print(f"{'pairwise dist std/mean':<40} "
          f"{d_5k_dist.std()/d_5k_dist.mean():>10.3f} "
          f"{d_20k_dist.std()/d_20k_dist.mean():>10.3f} "
          f"{d_u_dist.std()/d_u_dist.mean():>10.3f}")
    print(f"{'k=50 cluster mean radius':<40} "
          f"{r5[3]['mean_r']:>10.3f} {r20[3]['mean_r']:>10.3f} {ru[3]['mean_r']:>10.3f}")
    print(f"{'expected perturb radius':<40} {np.sqrt(18)*0.2:>10.3f}")


if __name__ == "__main__":
    main()
